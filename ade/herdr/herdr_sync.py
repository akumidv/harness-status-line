#!/usr/bin/env python3
"""Sync the Herdr customizations kept here with a Herdr app home (default ~/.config/herdr-app).

The repository is the source of truth: edit here, then `deploy`.
`extract` exists only to bring back an edit made in place (in the app home).

  python3 herdr_sync.py status            what differs between the repo and the app home
  python3 herdr_sync.py deploy [--dry-run] repo -> app home (backs up what it replaces, runs `herdr-app check`)
  python3 herdr_sync.py extract [--dry-run] app home -> repo

`--repo DIR` (before or after the command) takes mods/ and layouts/ from DIR instead of this folder
(herdr_transfer.py deploys an unpacked bundle that way).

What is synced: every folder under mods/ (one Herdr mod each), every file under layouts/ and under themes/.
Herdr's own files in a mod folder (gpui-kit.d.ts, written by Herdr) are never copied.
Layouts: panel-shell rewrites the stack `panel-shell-term` (the dock's tabs) at run time, so it is
compared as a placeholder and the live value is kept on deploy. Layout files are
written directly, never through `layout.set`, which would drop the layout's clicks
(layouts/.state/<name>.json: panel shown, sizes, the selected stack child).
"""
import argparse
import filecmp
import json
import os
import shutil
import subprocess
import sys
import time
from pathlib import Path

REPO = Path(__file__).resolve().parent
LIVE = Path(os.environ.get("HERDR_APP_HOME") or Path.home() / ".config/herdr-app")
BACKUPS = Path(os.environ.get("XDG_STATE_HOME") or Path.home() / ".local/state") / "ai_env/backups/herdr"
STAMP = time.strftime("%Y%m%d-%H%M%S")
HERDR_OWNED = {"gpui-kit.d.ts"}           # regenerated by Herdr in each mod folder
VOLATILE = {"panel-shell-term"}  # layout nodes panel-shell rewrites at run time (the dock's tabs)
PLACEHOLDER = {"type": "stack", "children": []}
KEEP = {"id", "size", "min", "max", "background", "radius", "border", "padding"}  # layout fields of such a node


def mod_files(folder):
    if not folder.is_dir():
        return set()
    return {p.relative_to(folder).as_posix() for p in folder.rglob("*")
            if p.is_file() and not p.is_symlink() and p.name not in HERDR_OWNED and "__pycache__" not in p.parts}


def walk(node):
    yield node
    for child in node.get("children", []) or []:
        yield from walk(child)


def volatile(tree):
    """{node id: its run-time part} for the nodes panel-shell rewrites."""
    return {n["id"]: {k: v for k, v in n.items() if k not in KEEP} for n in walk(tree) if n.get("id") in VOLATILE}


def set_volatile(tree, values):
    for n in walk(tree):
        if n.get("id") in values:
            for k in [k for k in n if k not in KEEP]:
                del n[k]
            n.update(values[n["id"]])
    return tree


def layout_text(tree):
    return json.dumps(tree, indent=2, ensure_ascii=False) + "\n"


def normalized(path):
    tree = json.loads(path.read_text())
    return set_volatile(tree, {k: dict(PLACEHOLDER) for k in volatile(tree)})


def pairs():
    """(kind, repo path, live path) for everything either side has."""
    out = []
    for folder in sorted({p.name for p in (REPO / "mods").iterdir() if p.is_dir()}):
        r, l = REPO / "mods" / folder, LIVE / "mods" / folder
        for rel in sorted(mod_files(r) | mod_files(l)):
            out.append(("mod", r / rel, l / rel))
    for p in sorted((REPO / "layouts").glob("*.json")):
        out.append(("layout", p, LIVE / "layouts" / p.name))
    for p in sorted((REPO / "themes").glob("*.json")):
        out.append(("theme", p, LIVE / "themes" / p.name))
    return out


def same(kind, r, l):
    if not (r.exists() and l.exists()):
        return False
    if kind == "layout":
        return normalized(r) == normalized(l)
    return filecmp.cmp(r, l, shallow=False)


def status(_args):
    dirty = 0
    for kind, r, l in pairs():
        name = r.relative_to(REPO).as_posix()
        state = ("in sync" if same(kind, r, l) else "missing in app home" if not l.exists()
                 else "only in app home (extract to keep)" if not r.exists() else "differs")
        dirty += state != "in sync"
        print(f"  {state:<36} {name}")
    print(f"app home: {LIVE}\n{'everything in sync' if not dirty else f'{dirty} file(s) differ'}")
    return 0 if not dirty else 1


def backup(path):
    dest = BACKUPS / STAMP / path.relative_to(LIVE)
    dest.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(path, dest)


def deploy(args):
    changed_mods = set()
    for kind, r, l in pairs():
        if not r.exists() or same(kind, r, l):
            continue
        print(f"  {r.relative_to(REPO).as_posix()} -> {l}")
        if args.dry_run:
            continue
        l.parent.mkdir(parents=True, exist_ok=True)
        if l.exists():
            backup(l)
        if kind == "layout":
            tree = json.loads(r.read_text())
            keep = volatile(json.loads(l.read_text())) if l.exists() else {}
            l.write_text(layout_text(set_volatile(tree, keep)))
        else:
            shutil.copy2(r, l)
            if kind == "mod":
                changed_mods.add(r.relative_to(REPO / "mods").parts[0])
    if args.dry_run:
        return 0
    if (BACKUPS / STAMP).exists():
        print(f"replaced files backed up in {BACKUPS / STAMP}")
    failed = 0
    if changed_mods and shutil.which("herdr-app"):
        for mod in sorted(changed_mods):
            res = subprocess.run(["herdr-app", "check", f"mods/{mod}"], cwd=LIVE, capture_output=True, text=True)
            lines = [x for x in (res.stdout + res.stderr).splitlines() if x.strip() and not any(w in x for w in ("libEGL", "MESA", "WARN"))]
            print(f"  check {mod}: {lines[-1] if lines else ('passed' if res.returncode == 0 else 'failed')}")
            failed += res.returncode != 0
    return 1 if failed else 0


def extract(args):
    for kind, r, l in pairs():
        if not l.exists() or same(kind, r, l):
            continue
        print(f"  {l} -> {r.relative_to(REPO).as_posix()}")
        if args.dry_run:
            continue
        r.parent.mkdir(parents=True, exist_ok=True)
        if kind == "layout":
            r.write_text(layout_text(normalized(l)))
        else:
            shutil.copy2(l, r)
    return 0


def main():
    global REPO
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", choices=["status", "deploy", "extract"])
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--repo", type=Path, default=REPO, help="folder holding mods/ and layouts/ (default: this folder)")
    args = ap.parse_args()
    REPO = args.repo.resolve()
    if not REPO.is_dir():
        sys.exit(f"--repo {args.repo} is not a folder")
    if not LIVE.is_dir():
        sys.exit(f"no Herdr app home at {LIVE} (install Herdr first, or set HERDR_APP_HOME)")
    sys.exit({"status": status, "deploy": deploy, "extract": extract}[args.command](args))


if __name__ == "__main__":
    main()
